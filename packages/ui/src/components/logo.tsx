// ─── Public Logo component ────────────────────────────────────────────────────

export type LogoVariant = "icon" | "wordmark" | "full";
export type LogoLocale = "ar" | "en";

export interface LogoProps {
  /** "icon" = mark only, "wordmark" = text only, "full" = mark + text */
  variant?: LogoVariant;
  locale?: LogoLocale;
  className?: string;
  iconClassName?: string;
  wordmarkClassName?: string;
}

export function Logo({
  variant = "full",
  locale = "en",
  className,
  iconClassName,
  wordmarkClassName,
}: LogoProps) {
  if (variant === "icon") {
    return <LogoIcon className={cn(className, iconClassName)} />;
  }

  if (variant === "wordmark") {
    return locale === "ar" ? (
      <LogoAr className={cn(className, wordmarkClassName)} />
    ) : (
      <LogoEn className={cn(className, wordmarkClassName)} />
    );
  }

  // "full" — icon + wordmark side by side
  return (
    <div className={cn("flex items-center gap-3", className)}>
      <LogoIcon className={iconClassName} />
      {locale === "ar" ? (
        <LogoAr className={wordmarkClassName} />
      ) : (
        <LogoEn className={wordmarkClassName} />
      )}
    </div>
  );
}
